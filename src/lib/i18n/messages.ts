export type MessageKey = keyof typeof portuguese;
export type Locale = "en-CA" | "pt-BR";
export type MessageValues = Record<string, string | number>;
export type Message = MessageKey | { key: MessageKey; values?: MessageValues };

export function translate(locale: Locale, message: Message, values?: MessageValues): string {
  const key = typeof message === "string" ? message : message.key;
  const parameters = typeof message === "string" ? values : message.values;
  const template = locale === "pt-BR" ? portuguese[key] ?? key : key;
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    String(parameters?.[name] ?? placeholder),
  );
}

export class TranslatableError extends Error {
  constructor(public readonly translation: Message) {
    super(translate("en-CA", translation));
  }
}

export function errorMessage(error: unknown, fallback: MessageKey): Message {
  return error instanceof TranslatableError ? error.translation : fallback;
}

// Attribute markers are only for Astro-owned DOM; React translates its own props.
export function translatedAttributes(messages: Record<string, Message>) {
  return Object.fromEntries(Object.entries(messages).flatMap(([attribute, message]) => [
    [attribute, translate("en-CA", message)],
    [`data-i18n-${attribute}`, JSON.stringify(message)],
  ]));
}
